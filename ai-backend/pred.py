finbert = None


if ENABLE_SENTIMENT:

    try:

        import torch

        from transformers import (
            AutoTokenizer,
            AutoModelForSequenceClassification
        )

        from torch.nn.functional import (
            softmax
        )


        class FinBERTAnalyzer:

            LABELS = {

                0: "positive",

                1: "negative",

                2: "neutral"

            }


            SCORES = {

                "positive": 1.0,

                "negative": -1.0,

                "neutral": 0.0

            }


            def __init__(
                self,
                model_name="ProsusAI/finbert"
            ):

                self.device = torch.device(

                    "cuda"
                    if torch.cuda.is_available()
                    else "cpu"

                )

                log.info(
                    f"Loading FinBERT on "
                    f"{self.device}"
                )


                self.tok = (
                    AutoTokenizer
                    .from_pretrained(
                        model_name
                    )
                )


                self.model = (
                    AutoModelForSequenceClassification
                    .from_pretrained(
                        model_name
                    )
                    .to(self.device)
                    .eval()
                )


                log.info(
                    "✅ FinBERT loaded"
                )


            def analyze_headline(
                self,
                headline
            ):

                inputs = self.tok(

                    headline,

                    return_tensors="pt",

                    truncation=True,

                    max_length=512,

                    padding=True

                )


                inputs = {
                    k: v.to(self.device)
                    for k, v in inputs.items()
                }


                with torch.no_grad():

                    logits = (
                        self.model(
                            **inputs
                        ).logits
                    )


                probs = (
                    softmax(
                        logits,
                        dim=-1
                    )
                    .cpu()
                    .numpy()[0]
                )


                idx = int(
                    np.argmax(
                        probs
                    )
                )


                label = (
                    self.LABELS[idx]
                )


                return {

                    "headline":
                        headline,

                    "label":
                        label,

                    "score":
                        self.SCORES[label],

                    "confidence":
                        float(
                            probs[idx]
                        )

                }


            def analyze_batch(
                self,
                headlines
            ):

                if not headlines:

                    return {

                        "avg_score":
                            0.0,

                        "sentiment_label":
                            "Neutral",

                        "results":
                            []

                    }


                results = [

                    self.analyze_headline(
                        h
                    )

                    for h in headlines

                ]


                avg = float(
                    np.mean(
                        [
                            r["score"]
                            for r in results
                        ]
                    )
                )


                if avg > 0.1:

                    label = "Positive"

                elif avg < -0.1:

                    label = "Negative"

                else:

                    label = "Neutral"


                return {

                    "avg_score":
                        avg,

                    "sentiment_label":
                        label,

                    "results":
                        results

                }


        finbert = FinBERTAnalyzer()


    except Exception as e:

        log.exception(
            "FinBERT could not be loaded."
        )

        raise RuntimeError(
            "ENABLE_SENTIMENT=true but "
            "FinBERT initialization failed. "
            "Install torch/transformers and "
            "make sure the FinBERT model can be loaded."
        ) from e


