def fetch_news_headlines(
    ticker_obj,
    max_headlines=10
):

    try:

        news = (
            ticker_obj.news
            or []
        )


        headlines = []


        for item in news[
            :max_headlines
        ]:

            content = (
                item.get(
                    "content",
                    item
                )
            )


            title = (

                content.get("title")

                or

                content.get("headline")

                or

                content.get("summary")

                or

                ""

            )


            if title:

                headlines.append(
                    title.strip()
                )


        return headlines


    except Exception as e:

        log.warning(
            f"Could not fetch news: {e}"
        )

        return []


