# IMPORTANT:
# This replaces the old feature function.
#
# No untrained indicators are calculated.
#
# ============================================================

def create_stationary_features(
    df: pd.DataFrame
) -> pd.DataFrame:

    df = (
        df
        .sort_values("Date")
        .copy()
    )


    close = df["Close"]

    high = df["High"]

    low = df["Low"]


    # ========================================================
    # EMA20
    # ========================================================

    ema20 = (
        ta.trend.EMAIndicator(

            close=close,

            window=20

        )
        .ema_indicator()
    )


    # ========================================================
    # EMA50
    # ========================================================

    ema50 = (
        ta.trend.EMAIndicator(

            close=close,

            window=50

        )
        .ema_indicator()
    )


    # ========================================================
    # RSI14
    # ========================================================

    rsi14 = (
        ta.momentum.RSIIndicator(

            close=close,

            window=14

        )
        .rsi()
    )


    # ========================================================
    # ATR14
    # ========================================================

    atr14 = (
        ta.volatility.AverageTrueRange(

            high=high,

            low=low,

            close=close,

            window=14

        )
        .average_true_range()
    )


    # ========================================================
    # EMA20 FEATURES
    # ========================================================

    df["EMA20_DISTANCE"] = (

        close / ema20

    ) - 1.0


    df["EMA20_SLOPE"] = (

        ema20 /
        ema20.shift(5)

    ) - 1.0


    df["EMA20_ACCEL"] = (

        df["EMA20_SLOPE"]
        .diff(5)

    )


    # ========================================================
    # EMA50 FEATURES
    # ========================================================

    df["EMA50_DISTANCE"] = (

        close / ema50

    ) - 1.0


    df["EMA50_SLOPE"] = (

        ema50 /
        ema50.shift(5)

    ) - 1.0


    df["EMA50_ACCEL"] = (

        df["EMA50_SLOPE"]
        .diff(5)

    )


    # ========================================================
    # EMA RELATIONSHIP
    # ========================================================

    df["EMA_SPREAD"] = (

        ema20 /
        ema50

    ) - 1.0


    df["EMA_SPREAD_SLOPE"] = (

        df["EMA_SPREAD"]
        .diff(5)

    )


    df["EMA_ALIGNMENT"] = np.where(

        ema20 > ema50,

        1.0,

        -1.0

    )


    # ========================================================
    # RSI FEATURES
    # ========================================================

    df["RSI14"] = (

        rsi14 - 50.0

    ) / 50.0


    df["RSI_SLOPE"] = (

        rsi14.diff(5)

    ) / 100.0


    df["RSI_ACCEL"] = (

        rsi14
        .diff(5)
        .diff(5)

    ) / 100.0


    # ========================================================
    # ATR FEATURES
    # ========================================================

    df["ATR14_N"] = (

        atr14 / close

    )


    df["ATR_SLOPE"] = (

        df["ATR14_N"]
        .pct_change(5)

    )


    df["ATR_ACCEL"] = (

        df["ATR_SLOPE"]
        .diff(5)

    )


    # ========================================================
    # CLEAN
    # ========================================================

    df.replace(

        [
            np.inf,
            -np.inf
        ],

        np.nan,

        inplace=True

    )


    return df


# ============================================================
# HYBRID SCORE
# ============================================================

def compute_hybrid_score(
    prob_up,
    sentiment_avg
):

    sentiment_norm = (

        sentiment_avg + 1.0

    ) / 2.0


    combined = float(

        np.clip(

            WEIGHT_MODEL *
            prob_up
            +

            WEIGHT_SENTIMENT *
            sentiment_norm,

            0.0,

            1.0

        )

    )


    if combined >= BUY_THRESHOLD:

        recommendation = "BUY"

    elif combined <= SELL_THRESHOLD:

        recommendation = "SELL"

    else:

        recommendation = "HOLD"


    return (
        combined,
        recommendation
    )


