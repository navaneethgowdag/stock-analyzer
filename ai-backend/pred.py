# LOAD CACHED HISTORY
# ============================================================

def load_cached_history(
    conn,
    ticker: str
):

    with conn.cursor() as cur:

        cur.execute(
            """
            SELECT

                date,
                open,
                high,
                low,
                close,
                volume

            FROM stock_history

            WHERE ticker = %s

            ORDER BY date;

            """,

            (ticker,)

        )


        rows = cur.fetchall()


    if not rows:

        return None


    df = pd.DataFrame(

        rows,

        columns=[

            "Date",
            "Open",
            "High",
            "Low",
            "Close",
            "Volume"

        ]

    )


    df["Date"] = pd.to_datetime(
        df["Date"]
    )


    for column in [

        "Open",
        "High",
        "Low",
        "Close",
        "Volume"

    ]:

        df[column] = pd.to_numeric(
            df[column],
            errors="coerce"
        )


    return df


# ============================================================
# SAVE STOCK HISTORY
# ============================================================

def save_stock_history(
    conn,
    ticker: str,
    df: pd.DataFrame
):

    if df is None or df.empty:

        return


    records = []


    for _, row in df.iterrows():

        volume = row[
            "Volume"
        ]


        if pd.isna(volume):

            volume = 0


        records.append(

            (
                ticker,

                pd.Timestamp(
                    row["Date"]
                ).date(),

                float(
                    row["Open"]
                ),

                float(
                    row["High"]
                ),

                float(
                    row["Low"]
                ),

                float(
                    row["Close"]
                ),

                int(volume)

            )

        )


    if not records:

        return


    with conn.cursor() as cur:

        psycopg2.extras.execute_values(

            cur,

            """
            INSERT INTO stock_history
            (
                ticker,
                date,
                open,
                high,
                low,
                close,
                volume
            )

            VALUES %s

            ON CONFLICT
            (
                ticker,
                date
            )

            DO UPDATE SET

                open =
                    EXCLUDED.open,

                high =
                    EXCLUDED.high,

                low =
                    EXCLUDED.low,

                close =
                    EXCLUDED.close,

                volume =
                    EXCLUDED.volume;

            """,

            records

        )


    conn.commit()


# ============================================================
# NORMALIZE YFINANCE
# ============================================================

def normalize_ohlcv(
    raw: pd.DataFrame
):

    if raw is None or raw.empty:

        return pd.DataFrame()


    df = raw.copy()


    if isinstance(
        df.columns,
        pd.MultiIndex
    ):

        df.columns = [

            c[0]
            for c in df.columns

        ]


    df = (
        df
        .reset_index()
    )


    if (
        "Date"
        not in
        df.columns
    ):

        if (
            "index"
            in
            df.columns
        ):

            df.rename(
                columns={
                    "index": "Date"
                },
                inplace=True
            )


    required = [

        "Date",
        "Open",
        "High",
        "Low",
        "Close",
        "Volume"

    ]


    missing = [

        c
        for c in required
        if c not in df.columns

    ]


    if missing:

        raise ValueError(
            f"Missing OHLCV columns: "
            f"{missing}"
        )


    df = df[
        required
    ].copy()


    df["Date"] = (
        pd.to_datetime(
            df["Date"]
        )
        .dt.tz_localize(None)
    )


    for column in [

        "Open",
        "High",
        "Low",
        "Close",
        "Volume"

    ]:

        df[column] = pd.to_numeric(
            df[column],
            errors="coerce"
        )


    df.dropna(
        subset=[
            "Open",
            "High",
            "Low",
            "Close"
        ],
        inplace=True
    )


    df.drop_duplicates(
        subset=["Date"],
        keep="last",
        inplace=True
    )


    return (
        df
        .sort_values("Date")
        .reset_index(drop=True)
    )


# ============================================================
# GET / UPDATE HISTORY
# ============================================================

def get_stock_history(
    conn,
    ticker
):

    cached = load_cached_history(
        conn,
        ticker
    )


    # ========================================================
    # COLD START
    # ========================================================

    if cached is None or cached.empty:

        log.info(
            f"{ticker}: "
            f"cold-start download "
            f"({LOOKBACK_PERIOD})"
        )


        raw = yf.download(

            ticker,

            period=LOOKBACK_PERIOD,

            interval="1d",

            progress=False,

            auto_adjust=True,

            threads=False

        )


        fetched = normalize_ohlcv(
            raw
        )


    # ========================================================
    # INCREMENTAL
    # ========================================================

    else:

        latest_date = (
            cached[
                "Date"
            ].max()
        )


        # Download a few days of overlap
        # so revised bars are captured.

        start_date = (

            latest_date
            - pd.Timedelta(
                days=3
            )

        ).strftime(
            "%Y-%m-%d"
        )


        log.info(
            f"{ticker}: "
            f"incremental download "
            f"from {start_date}"
        )


        raw = yf.download(

            ticker,

            start=start_date,

            interval="1d",

            progress=False,

            auto_adjust=True,

            threads=False

        )


        fetched = normalize_ohlcv(
            raw
        )


    # ========================================================
    # STORE NEW DATA
    # ========================================================

    if not fetched.empty:

        save_stock_history(

            conn,

            ticker,

            fetched

        )


    # ========================================================
    # MERGE
    # ========================================================

    if cached is None or cached.empty:

        history = fetched

    else:

        history = pd.concat(

            [
                cached,
                fetched
            ],

            ignore_index=True

        )


    if history.empty:

        return pd.DataFrame()


    history = (

        history

        .drop_duplicates(
            subset=["Date"],
            keep="last"
        )

        .sort_values("Date")

        .reset_index(drop=True)

    )


    # Keep the same 2-year deployment lookback.

    max_date = (
        history["Date"].max()
    )


    history = history[
        history["Date"]
        >=
        (
            max_date
            - pd.Timedelta(
                days=730
            )
        )
    ].copy()


    history.reset_index(
        drop=True,
        inplace=True
    )


    return history


# ============================================================
# GET TRAINED MODEL
# ============================================================

def get_model_for_ticker(
    ticker
):

    if ticker not in portfolio_models:

        return None, None


    model_entry = (
        portfolio_models[
            ticker
        ]
    )


    # --------------------------------------------------------
    # Current training format:
    #
    # {
    #     "model": calibrated_model,
    #     "base_model": xgb_model,
    #     "confidence_threshold": ...
    # }
    #
    # --------------------------------------------------------

    if isinstance(
        model_entry,
        dict
    ):

        model = model_entry.get(
            "model"
        )


        threshold = model_entry.get(

            "confidence_threshold",

            model_entry.get(
                "threshold",
                0.50
            )

        )


    else:

        # Compatibility with older pkl files

        model = model_entry

        threshold = 0.50


    if model is None:

        return None, None


    return (
        model,
        float(threshold)
    )


# ============================================================
# PROCESS TICKER
# ============================================================

def process_ticker(
    symbol: str,
    exchange: str,
    conn
):

    ticker = yahoo_ticker(
        symbol,
        exchange
    )


    # ========================================================
    # ONLY USE TRAINED STOCKS
    # ========================================================

    if ticker not in portfolio_models:

        log.warning(
            f"No trained model for "
            f"{ticker}, skipping."
        )

        return None


    model, confidence_threshold = (
        get_model_for_ticker(
            ticker
        )
    )


    if model is None:

        log.warning(
            f"No usable model for "
            f"{ticker}, skipping."
        )

        return None


    # ========================================================
    # LOAD HISTORY
    # ========================================================

    hist = get_stock_history(

        conn,

        ticker

    )


    if hist.empty:

        log.warning(
            f"{ticker}: "
            f"No historical data."
        )

        return None


    if len(hist) < MIN_HISTORY_ROWS:

        log.warning(
            f"{ticker}: "
            f"Only {len(hist)} rows. "
            f"Need {MIN_HISTORY_ROWS}."
        )

        return None


    # ========================================================
    # EXACT TRAINED FEATURE ENGINEERING
    # ========================================================

    eng = (
        create_stationary_features(
            hist
        )
    )


    eng.replace(

        [
            np.inf,
            -np.inf
        ],

        np.nan,

        inplace=True

    )


    valid = (
        eng
        .dropna(
            subset=feature_columns
        )
        .sort_values("Date")
    )


    if valid.empty:

        log.warning(
            f"{ticker}: "
            f"No valid model features."
        )

        return None


    latest = (
        valid
        .iloc[[-1]]
        .copy()
    )


    X_in = latest[
        feature_columns
    ]


    # ========================================================
    # MACHINE-LEARNING PREDICTION
    # ========================================================

    probabilities = (
        model
        .predict_proba(
            X_in
        )[0]
    )


    prob_down = float(
        probabilities[0]
    )


    prob_up = float(
        probabilities[1]
    )


    # ========================================================
    # HIGH-CONFIDENCE MODEL SIGNAL
    # ========================================================

    if (
        prob_up
        >=
        confidence_threshold
    ):

        pred_direction = "UP"


    elif (
        prob_down
        >=
        confidence_threshold
    ):

        pred_direction = "DOWN"


    else:

        pred_direction = "NO SIGNAL"


    # ========================================================
    # LIVE PRICE
    # ========================================================

    ticker_obj = (
        yf.Ticker(
            ticker
        )
    )


    last_close = float(
        latest[
            "Close"
        ].iloc[0]
    )


    previous_close = None


    if len(hist) >= 2:

        previous_close = float(

            hist[
                "Close"
            ].iloc[-2]

        )


    try:

        price = float(
            ticker_obj
            .fast_info
            .last_price
        )


        if (
            np.isnan(price)
            or
            price <= 0
        ):

            raise ValueError


    except Exception:

        price = last_close


    try:

        live_previous = float(

            ticker_obj
            .fast_info
            .previous_close

        )


        if (

            not np.isnan(
                live_previous
            )

            and

            live_previous > 0

        ):

            previous_close = (
                live_previous
            )


    except Exception:

        pass


    # ========================================================
    # FINBERT SENTIMENT
    # ========================================================

    sentiment = {

        "avg_score": 0.0,

        "sentiment_label":
            "Neutral",

        "results": []

    }


    if finbert is not None:

        headlines = (
            fetch_news_headlines(

                ticker_obj,

                max_headlines=
                    MAX_HEADLINES

            )
        )


        sentiment = (
            finbert
            .analyze_batch(
                headlines
            )
        )


    # ========================================================
    # HYBRID SCORE
    # ========================================================
    #
    # FinBERT does NOT enter the XGBoost model.
    #
    # It is a separate downstream signal.
    #
    # ========================================================

    combined_score, recommendation = (
        compute_hybrid_score(

            prob_up,

            sentiment[
                "avg_score"
            ]

        )
    )


    # ========================================================
    # RETURN RESULT
    # ========================================================

    return {

        "ticker":
            ticker,

        "symbol":
            symbol,

        "exchange":
            exchange,

        "current_price":
            round(
                price,
                2
            ),

        "previous_close":
            (
                round(
                    previous_close,
                    2
                )

                if previous_close
                is not None

                else None
            ),

        "prob_up":
            round(
                prob_up,
                4
            ),

        "pred_direction":
            pred_direction,

        "sentiment_label":
            sentiment[
                "sentiment_label"
            ],

        "sentiment_score":
            round(
                sentiment[
                    "avg_score"
                ],
                4
            ),

        "combined_score":
            round(
                combined_score,
                4
            ),

        "recommendation":
            recommendation,

        "news_results":
            sentiment[
                "results"
            ]

    }


# ============================================================
# UPSERT PREDICTION
# ============================================================
#
# IMPORTANT:
# Existing database uses:
#     pred_direction
#
# NOT:
#     prediction
#
# This fixes the PostgreSQL error you encountered.
#
# ============================================================

def upsert_prediction(
    conn,
    row: dict
):

    with conn.cursor() as cur:

        cur.execute(

            """
            INSERT INTO predictions
            (
                ticker,
                symbol,
                exchange,
                current_price,
                previous_close,
                prob_up,
                pred_direction,
                sentiment_label,
                sentiment_score,
                combined_score,
                recommendation,
                updated_at
            )

            VALUES
            (
                %(ticker)s,
                %(symbol)s,
                %(exchange)s,
                %(current_price)s,
                %(previous_close)s,
                %(prob_up)s,
                %(pred_direction)s,
                %(sentiment_label)s,
                %(sentiment_score)s,
                %(combined_score)s,
                %(recommendation)s,
                NOW()
            )

            ON CONFLICT (ticker)

            DO UPDATE SET

                symbol =
                    EXCLUDED.symbol,

                exchange =
                    EXCLUDED.exchange,

                current_price =
                    EXCLUDED.current_price,

                previous_close =
                    EXCLUDED.previous_close,

                prob_up =
                    EXCLUDED.prob_up,

                pred_direction =
                    EXCLUDED.pred_direction,

                sentiment_label =
                    EXCLUDED.sentiment_label,

                sentiment_score =
                    EXCLUDED.sentiment_score,

                combined_score =
                    EXCLUDED.combined_score,

                recommendation =
                    EXCLUDED.recommendation,

                updated_at =
                    NOW();

            """,

            row

        )


    conn.commit()


