def insert_news_sentiment(
    conn,
    ticker: str,
    results: list
):

    if not results:

        return


    with conn.cursor() as cur:

        psycopg2.extras.execute_values(

            cur,

            """
            INSERT INTO news_sentiment
            (
                ticker,
                headline,
                label,
                score,
                confidence,
                created_at
            )

            VALUES %s

            ON CONFLICT (
                ticker,
                headline
            )

            DO UPDATE SET

                label =
                    EXCLUDED.label,

                score =
                    EXCLUDED.score,

                confidence =
                    EXCLUDED.confidence,

                created_at =
                    NOW();

            """,

            [

                (

                    ticker,

                    result[
                        "headline"
                    ],

                    result[
                        "label"
                    ],

                    result[
                        "score"
                    ],

                    result[
                        "confidence"
                    ],

                    datetime.now()

                )

                for result in results

            ]

        )


    conn.commit()


