def insert_alert(
    conn,
    ticker,
    alert_type,
    title,
    message,
    severity,
    value=None,
    reference_id=None
):

    with conn.cursor() as cur:

        if reference_id:

            cur.execute(

                """
                SELECT id

                FROM alerts

                WHERE ticker = %s

                AND alert_type = %s

                AND reference_id = %s

                LIMIT 1;

                """,

                (
                    ticker,
                    alert_type,
                    reference_id
                )

            )


            if cur.fetchone():

                return


        cur.execute(

            """
            INSERT INTO alerts
            (
                ticker,
                alert_type,
                title,
                message,
                severity,
                value,
                reference_id,
                created_at
            )

            VALUES
            (
                %s,
                %s,
                %s,
                %s,
                %s,
                %s,
                %s,
                NOW()
            );

            """,

            (
                ticker,
                alert_type,
                title,
                message,
                severity,
                value,
                reference_id
            )

        )


    conn.commit()


