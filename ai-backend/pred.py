# ============================================================
# FULL WATCHLIST
# ============================================================
#
# Only stocks with trained models are included.
#
# ============================================================

def get_full_watchlist(
    conn
):

    combined = {}


    # --------------------------------------------------------
    # Nifty 50
    # --------------------------------------------------------

    for symbol in NIFTY_50_SYMBOLS:

        ticker = (
            symbol.upper()
            + ".NS"
        )


        if ticker not in portfolio_models:

            continue


        key = (

            symbol.upper(),

            "NSE"

        )


        combined[key] = {

            "symbol":
                symbol.upper(),

            "exchange":
                "NSE"

        }


    # --------------------------------------------------------
    # User watchlist
    # --------------------------------------------------------

    for entry in (
        get_user_watchlist(
            conn
        )
    ):

        symbol = (
            entry["symbol"]
            .strip()
            .upper()
        )


        exchange = (
            entry["exchange"]
            or
            "NSE"
        ).strip().upper()


        ticker = yahoo_ticker(

            symbol,

            exchange

        )


        # Don't predict untrained stocks

        if ticker not in portfolio_models:

            log.info(

                f"{ticker}: "
                f"no trained model, "
                f"skipping."

            )

            continue


        key = (

            symbol,

            exchange

        )


        combined[key] = entry


    return list(
        combined.values()
    )


# ============================================================
# MAIN JOB
# ============================================================

def run_job():
    log.info("Job started")

    conn = None

    try:
        # ====================================================
        # DATABASE CONNECTION
        # ====================================================

        log.info("Connecting to PostgreSQL...")

        db_host = parsed_db_url.hostname
        db_port = parsed_db_url.port or 5432

        log.info(
            f"Resolving DB host: "
            f"{db_host}:{db_port}"
        )

        try:
            addresses = socket.getaddrinfo(
                db_host,
                db_port,
                type=socket.SOCK_STREAM
            )

            log.info(
                f"Python resolved DB addresses: "
                f"{addresses}"
            )

        except socket.gaierror as e:

            log.error(
                f"Python DNS resolution failed: {e}"
            )

            raise


        # ====================================================
        # CONNECT
        # ====================================================

        conn = psycopg2.connect(
            DATABASE_URL,
            connect_timeout=15
        )

        log.info(
            "✅ PostgreSQL connection established"
        )


        # ====================================================
        # ENSURE DATABASE TABLES
        # ====================================================

        ensure_predictions_table(conn)

        ensure_news_sentiment_table(conn)

        ensure_price_history_table(conn)

        ensure_alerts_table(conn)

        ensure_stock_history_table(conn)


        # ====================================================
        # WATCHLIST
        # ====================================================

        watchlist = get_full_watchlist(
            conn
        )

        log.info(
            f"Stocks to process: "
            f"{len(watchlist)}"
        )


        if not watchlist:

            log.warning(
                "Stock universe is empty. "
                "Nothing to process."
            )

            return


        # ====================================================
        # COUNTERS
        # ====================================================

        processed = 0

        skipped = 0

        failed = 0


        # ====================================================
        # PROCESS STOCKS
        # ====================================================

        for entry in watchlist:

            symbol = entry[
                "symbol"
            ]

            exchange = entry[
                "exchange"
            ]


            log.info(
                f"Processing "
                f"{symbol}.{exchange} ..."
            )


            try:

                # ============================================
                # PREDICTION
                # ============================================

                result = process_ticker(

                    symbol,

                    exchange,

                    conn

                )


                if not result:

                    skipped += 1

                    log.warning(
                        f"Skipped "
                        f"{symbol}.{exchange}"
                    )

                    continue


                # ============================================
                # 1. SAVE ML + HYBRID PREDICTION
                # ============================================

                upsert_prediction(

                    conn,

                    result

                )


                # ============================================
                # 2. SAVE FINBERT NEWS SENTIMENT
                # ============================================

                insert_news_sentiment(

                    conn,

                    result[
                        "ticker"
                    ],

                    result[
                        "news_results"
                    ]

                )


                # ============================================
                # 3. GENERATE NEWS ALERTS
                # ============================================

                generate_news_alerts(

                    conn,

                    result

                )


                # ============================================
                # 4. SAVE PRICE HISTORY
                # ============================================

                insert_price_history(

                    conn,

                    result[
                        "ticker"
                    ],

                    result[
                        "current_price"
                    ]

                )


                # ============================================
                # 5. GENERATE PRICE ALERT
                # ============================================

                generate_price_alert(

                    conn,

                    result[
                        "ticker"
                    ],

                    result[
                        "current_price"
                    ]

                )


                # ============================================
                # SUCCESS
                # ============================================

                processed += 1


                log.info(

                    f"{result['ticker']}: "

                    f"MODEL="
                    f"{result['pred_direction']} | "

                    f"UP="
                    f"{result['prob_up']:.2%} | "

                    f"SENTIMENT="
                    f"{result['sentiment_label']} | "

                    f"SENTIMENT_SCORE="
                    f"{result['sentiment_score']:.2f} | "

                    f"COMBINED="
                    f"{result['combined_score']:.2%} | "

                    f"RECOMMENDATION="
                    f"{result['recommendation']} | "

                    f"PRICE="
                    f"{result['current_price']}"

                )


            except Exception as e:

                # ============================================
                # STOCK-LEVEL FAILURE
                # ============================================

                failed += 1


                log.exception(

                    f"Failed processing "
                    f"{symbol}.{exchange}: {e}"

                )


                # Important:
                # Clear failed PostgreSQL transaction so
                # the next stock can still be processed.

                try:

                    conn.rollback()

                except Exception:

                    pass


        # ====================================================
        # SUMMARY
        # ====================================================

        log.info(
            "=" * 70
        )

        log.info(
            "Prediction job summary"
        )

        log.info(
            f"Processed: {processed}"
        )

        log.info(
            f"Skipped  : {skipped}"
        )

        log.info(
            f"Failed   : {failed}"
        )

        log.info(
            "=" * 70
        )


    except Exception as e:

        # ====================================================
        # JOB-LEVEL FAILURE
        # ====================================================

        log.exception(
            f"Prediction job failed: {e}"
        )

        if conn is not None:

            try:

                conn.rollback()

            except Exception:

                pass

        raise


    finally:

        # ====================================================
        # CLOSE DATABASE
        # ====================================================

        if conn is not None:

            try:

                conn.close()

                log.info(
                    "PostgreSQL connection closed"
                )

            except Exception as e:

                log.warning(
                    f"Error closing PostgreSQL "
                    f"connection: {e}"
                )


    log.info(
        "Prediction job finished"
    )
# ============================================================
# ENTRY POINT
# ============================================================

if __name__ == "__main__":

    run_job()