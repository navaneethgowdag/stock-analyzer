# NEWS ALERTS
# ============================================================

def generate_news_alerts(
    conn,
    result: dict
):

    ticker = (
        result["ticker"]
    )


    news_results = (
        result.get(
            "news_results",
            []
        )
    )


    if not news_results:

        return


    for news in news_results:

        headline = (
            news
            .get(
                "headline",
                ""
            )
            .strip()
        )


        label = (
            str(
                news.get(
                    "label",
                    ""
                )
            )
            .strip()
            .lower()
        )


        score = float(
            news.get(
                "score",
                0
            )
            or
            0
        )


        confidence = float(
            news.get(
                "confidence",
                0
            )
            or
            0
        )


        if not headline:

            continue


        # ----------------------------------------------------
        # Strong positive news
        # ----------------------------------------------------

        if (

            label
            == "positive"

            and

            confidence
            >= 0.80

        ):

            insert_alert(

                conn=conn,

                ticker=ticker,

                alert_type="NEWS",

                title=(
                    f"Positive news "
                    f"for {ticker}"
                ),

                message=headline,

                severity="POSITIVE",

                value=score,

                reference_id=(
                    f"NEWS:"
                    f"{ticker}:"
                    f"{headline}"
                )

            )


        # ----------------------------------------------------
        # Strong negative news
        # ----------------------------------------------------

        elif (

            label
            == "negative"

            and

            confidence
            >= 0.80

        ):

            insert_alert(

                conn=conn,

                ticker=ticker,

                alert_type="NEWS",

                title=(
                    f"Negative news "
                    f"for {ticker}"
                ),

                message=headline,

                severity="NEGATIVE",

                value=score,

                reference_id=(
                    f"NEWS:"
                    f"{ticker}:"
                    f"{headline}"
                )

            )


# ============================================================
# PRICE ALERT
# ============================================================

def generate_price_alert(
    conn,
    ticker,
    current_price
):

    if (
        current_price is None
        or
        current_price <= 0
    ):

        return


    with conn.cursor() as cur:

        cur.execute(

            """
            SELECT price

            FROM price_history

            WHERE ticker = %s

            ORDER BY recorded_at DESC

            LIMIT 1 OFFSET 1;

            """,

            (ticker,)

        )


        row = cur.fetchone()


    if not row:

        return


    previous_price = float(
        row[0]
    )


    if previous_price <= 0:

        return


    change_percent = (

        (
            current_price
            -
            previous_price
        )
        /
        previous_price

    ) * 100


    if abs(
        change_percent
    ) < 3:

        return


    if change_percent > 0:

        alert_type = (
            "PRICE_SURGE"
        )

        severity = (
            "POSITIVE"
        )

        title = (
            f"{ticker} price surge"
        )

        message = (

            f"{ticker} increased by "
            f"{change_percent:.2f}% "
            f"from the previous recorded price."

        )

    else:

        alert_type = (
            "PRICE_DROP"
        )

        severity = (
            "NEGATIVE"
        )

        title = (
            f"{ticker} price drop"
        )

        message = (

            f"{ticker} decreased by "
            f"{abs(change_percent):.2f}% "
            f"from the previous recorded price."

        )


    insert_alert(

        conn=conn,

        ticker=ticker,

        alert_type=alert_type,

        title=title,

        message=message,

        severity=severity,

        value=round(
            change_percent,
            2
        ),

        reference_id=None

    )


